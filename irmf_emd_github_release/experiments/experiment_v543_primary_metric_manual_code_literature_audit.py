def run_v543_primary_metric_manual_code_literature_audit(output_dir):
    output_dir = ensure_dir(output_dir)
    rows = build_primary_metric_audit_rows()

    literature_counts = Counter(row["literature_status"] for row in rows)
    support_counts = Counter(row["reference_support_level"] for row in rows)
    status_counts = Counter(row["audit_status"] for row in rows)
    directions = Counter(row["direction"] for row in rows)
    dimensions = Counter(row["primary_dimension"] for row in rows)

    dashboard = {
        "audit_version": V543_AUDIT_VERSION,
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "audit_status": "complete_for_internal_protocol_pending_final_bibliography_binding",
        "primary_schema_source": "V5.28_normalized_spillover_primary_revision",
        "primary_endpoint_count": len(rows),
        "primary_dimension_count": len(dimensions),
        "paper_formula_equals_code_count": int(sum(bool(r["paper_formula_equals_code"]) for r in rows)),
        "construct_matches_formula_count": int(sum(bool(r["construct_matches_formula"]) for r in rows)),
        "controlled_sanity_or_standard_behavior_count": int(sum(bool(r["controlled_sanity_pass"]) for r in rows)),
        "direction_counts": dict(directions),
        "dimension_counts": dict(dimensions),
        "literature_status_counts": dict(literature_counts),
        "reference_support_level_counts": dict(support_counts),
        "audit_status_counts": dict(status_counts),
        "benchmark_results_recomputed": False,
        "algorithm_cube_rerun_required": False,
        "statistics_regeneration_required": False,
        "primary_schema_changed": False,
        "manual_citation_binding_required": True,
        "important_reviewer_notes": [
            "Current code uses signed noise_capture_corr, not absolute noise correlation.",
            "normalized_contamination_spillover_loss is derived as -log(contamination_spillover_score).",
            "Benchmark-defined metrics are not failed for lacking a direct formula clone in prior literature; they require construct clarity, code equality, behavioral validity, and method neutrality.",
        ],
    }

    write_csv(rows, output_dir / "primary_metric_manual_code_literature_audit.csv")
    write_json(rows, output_dir / "primary_metric_manual_code_literature_audit.json")
    write_json(dashboard, output_dir / "primary_metric_manual_code_literature_audit_dashboard.json")
    write_manifest(output_dir, {
        "audit_version": V543_AUDIT_VERSION,
        "artifact_role": "protocol_manual_code_literature_audit",
        "primary_endpoint_count": len(rows),
        "benchmark_results_recomputed": False,
        "statistics_regeneration_required": False,
    })
    return {
        "output_dir": str(output_dir),
        "dashboard": dashboard,
        "rows": rows,
    }

